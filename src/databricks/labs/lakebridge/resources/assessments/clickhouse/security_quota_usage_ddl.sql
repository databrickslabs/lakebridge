CREATE TABLE IF NOT EXISTS security_quota_usage (
    quota_name VARCHAR,
    quota_key VARCHAR,
    start_time TIMESTAMP,
    end_time TIMESTAMP,
    duration UBIGINT,
    queries UBIGINT,
    max_queries UBIGINT,
    query_selects UBIGINT,
    max_query_selects UBIGINT,
    query_inserts UBIGINT,
    max_query_inserts UBIGINT,
    errors UBIGINT,
    max_errors UBIGINT,
    result_rows UBIGINT,
    max_result_rows UBIGINT,
    result_bytes UBIGINT,
    max_result_bytes UBIGINT,
    read_rows UBIGINT,
    max_read_rows UBIGINT,
    read_bytes UBIGINT,
    max_read_bytes UBIGINT,
    execution_time DOUBLE,
    max_execution_time DOUBLE,
    written_bytes UBIGINT,
    max_written_bytes UBIGINT,
    failed_sequential_authentications UBIGINT,
    max_failed_sequential_authentications UBIGINT
);

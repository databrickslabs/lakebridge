CREATE TABLE IF NOT EXISTS security_quota_usage (
    quota_name VARCHAR,
    quota_key VARCHAR,
    start_time TIMESTAMP,
    end_time TIMESTAMP,
    duration BIGINT,
    queries BIGINT,
    max_queries BIGINT,
    query_selects BIGINT,
    max_query_selects BIGINT,
    query_inserts BIGINT,
    max_query_inserts BIGINT,
    errors BIGINT,
    max_errors BIGINT,
    result_rows BIGINT,
    max_result_rows BIGINT,
    result_bytes BIGINT,
    max_result_bytes BIGINT,
    read_rows BIGINT,
    max_read_rows BIGINT,
    read_bytes BIGINT,
    max_read_bytes BIGINT,
    execution_time DOUBLE,
    max_execution_time DOUBLE,
    written_bytes BIGINT,
    max_written_bytes BIGINT,
    failed_sequential_authentications BIGINT,
    max_failed_sequential_authentications BIGINT
);

    QUEUED_PROVISIONING_TIME DOUBLE,
    QUEUED_REPAIR_TIME DOUBLE,
    QUEUED_OVERLOAD_TIME DOUBLE,
    TRANSACTION_BLOCKED_TIME DOUBLE,
    BYTES_SCANNED DOUBLE,
    BYTES_WRITTEN DOUBLE,
    BYTES_SPILLED_TO_LOCAL_STORAGE DOUBLE,
    BYTES_SPILLED_TO_REMOTE_STORAGE DOUBLE,
    ROWS_PRODUCED DOUBLE,
    CREDITS_USED_CLOUD_SERVICES DOUBLE,

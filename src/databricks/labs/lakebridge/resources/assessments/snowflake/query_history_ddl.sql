    QUERY_TYPE VARCHAR,
    DATABASE_NAME VARCHAR,
    SCHEMA_NAME VARCHAR,
    USER_NAME VARCHAR,
    WAREHOUSE_NAME VARCHAR,
    WAREHOUSE_SIZE VARCHAR,

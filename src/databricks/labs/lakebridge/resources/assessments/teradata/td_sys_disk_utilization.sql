SELECT DATABASENAME,
    SUM(CAST(MAXPERM AS FLOAT)) / (1024 * 1024) MAX_PERM_MB,
    SUM(CAST(CURRENTPERM AS FLOAT)) / (1024 * 1024) CURRENT_PERM_MB,
    SUM(CAST(MAXSPOOL AS FLOAT)) / (1024 * 1024) MAX_SPOOL_MB,
    SUM(CAST(CURRENTSPOOL AS FLOAT)) / (1024 * 1024) CURRENT_SPOOL_MB
FROM DBC.DISKSPACEV
where DatabaseName NOT IN (
    'Crashdumps',
    'dbcmngr',
    'Default',
    'External_AP',
    'EXTUSER',
    'LockLogShredder',
    'PUBLIC',
    'Sys_Calendar',
    'SysAdmin',
    'SYSBAR',
    'SYSJDBC',
    'SYSLIB',
    'SystemFe',
    'SYSUDTLIB',
    'SYSUIF',
    'TD_SERVER_DB',
    'TDStats',
    'TD_SYSGPL',
    'TD_SYSXML',
    'TDMaps',
    'TDPUSER',
    'TDQCD',
    'tdwm',
    'SQLJ',
    'TD_SYSFNLIB',
    'SYSSPATIAL'
)
GROUP BY DATABASENAME;

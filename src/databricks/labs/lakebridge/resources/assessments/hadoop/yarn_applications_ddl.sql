CREATE TABLE yarn_applications (
    application_id VARCHAR,
    user_name VARCHAR,
    name VARCHAR,
    queue_name VARCHAR,
    application_type VARCHAR,
    state VARCHAR,
    final_status VARCHAR,
    progress DOUBLE,
    diagnostics VARCHAR,
    started_time TIMESTAMP,
    launch_time TIMESTAMP,
    finished_time TIMESTAMP,
    elapsed_time_ms BIGINT,
    allocated_mb BIGINT,
    allocated_vcores BIGINT,
    running_containers BIGINT,
    memory_seconds BIGINT,
    vcore_seconds BIGINT,
    preempted_resource_mb BIGINT,
    preempted_resource_vcores BIGINT,
    num_am_container_preempted BIGINT,
    num_non_am_container_preempted BIGINT,
    queue_usage_percentage DOUBLE,
    cluster_usage_percentage DOUBLE,
    log_aggregation_status VARCHAR,
    unmanaged_application BOOLEAN,
    priority BIGINT
)

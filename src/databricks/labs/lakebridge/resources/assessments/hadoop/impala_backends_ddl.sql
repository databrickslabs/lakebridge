    admit_mem_limit_bytes BIGINT,
    mem_reserved_bytes BIGINT,
    mem_admitted_bytes BIGINT,
    admission_slots BIGINT,
    admission_slots_in_use BIGINT,
    num_admitted BIGINT,
    process_start_time TIMESTAMP,
    version VARCHAR
)
